import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const get=p=>readFileSync(join(root,p));
const text=p=>get(p).toString('utf8');
const brand='assets/brand/';
const m=JSON.parse(text('docs/qa/figma-brand-transfer-20261025/brand-transfer-manifest.json'));
test('approved vector source retains all seven original house-and-card paths',()=>{
 const l=text(brand+'figma-originals/artwork-light.svg'),d=text(brand+'figma-originals/artwork-dark.svg');
 const paths=s=>[...s.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(x=>x[1]);
 assert.equal(paths(l).length,7);assert.deepEqual(paths(l),paths(d));
 assert.match(l,/#C29A62/i);assert.match(d,/#FFF9EC/i);
});
test('native and web render only transferred brand artwork',()=>{
 for(const p of ['src/brand.tsx','src/brand.web.tsx']){
   const s=text(p);assert.match(s,/logo-art-light\.png/);assert.match(s,/logo-art-dark\.png/);
   assert.doesNotMatch(s,/logo-color-(?:light|dark)\.png/);
 }
 assert.equal(m.placementCount,55);assert.equal(m.productionAuthorized,false);
});
test('required app and website icon assets exist with expected PNG dimensions',()=>{
 const assets=[['icon-light.png',1024],['icon-dark.png',1024],['icon-tinted.png',1024],['adaptive-color.png',1024],['adaptive-outline.png',1024],['logo-art-light.png',495]];
 for(const [name,width] of assets){const b=get(brand+name);assert.equal(b.toString('ascii',1,4),'PNG');assert.equal(b.readUInt32BE(16),width);}
 for(const [name,width] of [['favicon-light-32.png',32],['favicon-dark-32.png',32],['icon-512.png',512]]){const b=get('public/brand/'+name);assert.equal(b.readUInt32BE(16),width);}
 // Android native resources are generated by prebuild and must be verified against the built Android artifact, not assumed in an iOS-only source worktree.
 if(existsSync(join(root,'android'))) assert.ok(existsSync(join(root,'android/app/src/main/res/mipmap-hdpi/ic_launcher.webp')));
});
test('approved navigation assets are sourced exclusively from Figma SVG originals',()=>{
 const names=['home','memories','photos','reminders','find'];
 const source=text('src/accepted-navigation-icon.tsx');
 assert.doesNotMatch(source,/ui-icons\/accepted-v1/);
 for(const name of names){
  assert.match(source,new RegExp('figma-approved-v1/'+name+'\\.png'));
  const svg=text('assets/ui-icons/figma-originals-20261025/'+name+'.svg');
  const png=get('assets/ui-icons/figma-approved-v1/'+name+'.png');
  assert.match(svg,/<svg/);assert.equal(png.toString('ascii',1,4),'PNG');
  assert.equal(png.readUInt32BE(16),144);
 }
});
