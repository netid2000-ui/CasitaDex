from phone import *
name='QA Samsung Full Sweep 20261115'
route('add')
fill('Memory name (Required)',name)
fill('Description','Samsung air filter 20 x 25 x 1')
tap('Save')
node('Add Memory');shot('memory-created-home')
route('answers');fill('Search memories','20x25x1')
node('Open regular memory '+name);shot('normalized-search')
tap('With photos only');assert not any(b=='Open regular memory '+name for a,b in labels());shot('photos-only-filter')
tap('With photos only');tap('Open regular memory '+name)
tap('Edit memory');fill('Description','Samsung air filter 20 x 25 x 1 edited');tap('Save')
node('Edit memory');shot('memory-edited')
run('shell','am','force-stop',pkg);route('answers');fill('Search memories',name);tap('Open regular memory '+name)
node('Edit memory');shot('cold-restart')
airplane=run('shell','settings','get','global','airplane_mode_on').decode().strip()
try:
 run('shell','cmd','connectivity','airplane-mode','enable')
 route('answers');fill('Search memories',name);tap('Open regular memory '+name)
 tap('Edit memory');fill('Description','Samsung 20x25x1 saved offline');tap('Save')
 run('shell','am','force-stop',pkg);route('answers');fill('Search memories','20x25x1')
 tap('Open regular memory '+name);node('Edit memory')
 assert any('saved offline' in (a or '') for a,b in labels())
 shot('offline-edit-restart');print('Offline edit and restart PASS',flush=True)
finally:
 run('shell','cmd','connectivity','airplane-mode','enable' if airplane=='1' else 'disable')
tap('More ···');tap('Archive memory');shot('archived')
tap('More ···');tap('Return to Active');tap('More ···');tap('Move to Recently Deleted')
tap('Cancel');node('Edit memory');shot('delete-cancel')
tap('More ···');tap('Move to Recently Deleted');tap('Move to Recently Deleted')
node('Restore memory');shot('recently-deleted')
tap('Restore memory');node('Edit memory');shot('restored')
print('Memory lifecycle PASS',flush=True)
