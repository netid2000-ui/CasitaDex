import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
import { createHash } from "node:crypto";
const source=fs.readFileSync(new URL("../src/media-integrity.ts",import.meta.url),"utf8");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};
vm.runInNewContext(js,{module,exports:module.exports,Uint8Array,Error});
const {sniffImageMime,verifyMediaBytes}=module.exports;
const png=Uint8Array.from([137,80,78,71,13,10,26,10,0,0,0,0]);
const jpg=Uint8Array.from([255,216,255,224,1,2]);
const webp=Uint8Array.from([82,73,70,70,4,0,0,0,87,69,66,80]);
const sha=async b=>createHash("sha256").update(b).digest("hex");
const entry=(bytes,mime)=>({id:"a",cardId:"c",path:"media/a.png",mime,bytes:bytes.length,sha256:createHash("sha256").update(bytes).digest("hex")});
test("sniffs image signatures independently of claimed filename",()=>{assert.equal(sniffImageMime(png),"image/png");assert.equal(sniffImageMime(jpg),"image/jpeg");assert.equal(sniffImageMime(webp),"image/webp");assert.equal(sniffImageMime(Uint8Array.from([0,1])),null);});
test("accepts matching bytes signature length and real SHA256",async()=>{await verifyMediaBytes(entry(png,"image/png"),png,sha);});
test("rejects inconsistent byte length before digest",async()=>{let called=false;await assert.rejects(verifyMediaBytes({...entry(png,"image/png"),bytes:100},png,async()=>{called=true;return ""}),/count/);assert.equal(called,false);});
test("rejects disguised image before digest",async()=>{await assert.rejects(verifyMediaBytes(entry(png,"image/jpeg"),png,sha),/signature/);});
test("rejects changed bytes with stale digest",async()=>{const corrupt=Uint8Array.from(png);corrupt[10]=8;await assert.rejects(verifyMediaBytes(entry(png,"image/png"),corrupt,sha),/SHA-256/);});
test("rejects invalid calculated digest",async()=>{await assert.rejects(verifyMediaBytes(entry(png,"image/png"),png,async()=>"broken"),/SHA-256/);});